//! Bake the chiptune collection and the NTFS formatter into the executable.
//!
//! The Windows build shipped its `.xm` modules as RCDATA resources and leaned on
//! the operating system for everything else, so the program always carried what
//! it needed. This build script does the same for the two things a copied around
//! Linux binary would otherwise be missing:
//!
//! * every tracker module in `music/`, so a lone executable still has music;
//! * the NTFS formatter (`tools/ntfs/mkntfs` plus its `libntfs-3g.so.91`), so
//!   NTFS can be created even when `ntfsprogs` is not installed. The system copy
//!   is preferred at runtime when it exists.
//!
//! Both are optional. A checkout without `music/` or without `tools/ntfs/`
//! still builds; the generated lists are simply empty.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// The same extensions the runtime player accepts.
const EXTENSIONS: [&str; 4] = ["xm", "it", "mod", "s3m"];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));

    embed_music(&manifest, &out_dir);
    embed_ntfs(&manifest, &out_dir);
}

/// Every module in `music/`, as `EMBEDDED_TRACKS`.
fn embed_music(manifest: &Path, out_dir: &Path) {
    println!("cargo:rerun-if-changed=music");

    let music = manifest.join("music");
    let mut paths: Vec<PathBuf> = Vec::new();
    if let Ok(entries) = fs::read_dir(&music) {
        for entry in entries.flatten() {
            let path = entry.path();
            let playable = path
                .extension()
                .and_then(|e| e.to_str())
                .map(|e| EXTENSIONS.contains(&e.to_ascii_lowercase().as_str()))
                .unwrap_or(false);
            if playable && path.is_file() {
                paths.push(path);
            }
        }
    }
    paths.sort();

    let mut generated = String::new();
    generated.push_str("/// Every tracker module baked in at build time, as (label, bytes).\n");
    generated.push_str("pub static EMBEDDED_TRACKS: &[(&str, &[u8])] = &[\n");
    for path in &paths {
        let label = path
            .file_stem()
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_else(|| path.display().to_string());
        // `{:?}` produces a correctly quoted and escaped Rust string literal,
        // which is what both the label and the `include_bytes!` path need.
        let _ = writeln!(
            generated,
            "    ({:?}, include_bytes!({:?})),",
            label,
            absolute(path)
        );
    }
    generated.push_str("];\n");

    fs::write(out_dir.join("embedded_music.rs"), generated)
        .expect("could not write embedded_music.rs");
}

/// `tools/ntfs/mkntfs` and its library, as `MKNTFS` and `LIBNTFS`.
fn embed_ntfs(manifest: &Path, out_dir: &Path) {
    println!("cargo:rerun-if-changed=tools/ntfs");

    let dir = manifest.join("tools/ntfs");
    let mkntfs = dir.join("mkntfs");
    let library = dir.join("libntfs-3g.so.91");

    let mut generated = String::new();
    generated.push_str("// Generated by build.rs. Empty when tools/ntfs was absent.\n");
    if mkntfs.is_file() && library.is_file() {
        let _ = writeln!(
            generated,
            "pub static MKNTFS: &[u8] = include_bytes!({:?});",
            absolute(&mkntfs)
        );
        let _ = writeln!(
            generated,
            "pub static LIBNTFS: &[u8] = include_bytes!({:?});",
            absolute(&library)
        );
    } else {
        generated.push_str("pub static MKNTFS: &[u8] = &[];\n");
        generated.push_str("pub static LIBNTFS: &[u8] = &[];\n");
    }

    fs::write(out_dir.join("embedded_ntfs.rs"), generated)
        .expect("could not write embedded_ntfs.rs");
}

/// Absolute path so `include_bytes!` does not depend on the working directory.
fn absolute(path: &Path) -> String {
    fs::canonicalize(path)
        .unwrap_or_else(|_| path.to_path_buf())
        .to_string_lossy()
        .to_string()
}
